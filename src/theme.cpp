void ThemeSettings::LoadFrom(const Config& c) {
    brand = c.Get(L"theme.brand", brand);
    accent = c.Get(L"theme.accent", accent);
    backgroundPath = c.Get(L"theme.background", L"");
    timeoutSec = c.GetInt(L"theme.timeout", timeoutSec);
    win11Bypass = c.GetInt(L"theme.win11bypass", 1) != 0;
    aliases.clear();
    for (auto& p : c.kv) {
        if (p.first.rfind(L"alias.", 0) == 0) {
            AliasEntry e; e.relPath = p.first.substr(6); e.alias = p.second;
            e.unattendRel = c.Get(L"unattend." + e.relPath);
            aliases.push_back(e);
        }
    }
}
void ThemeSettings::SaveTo(Config& c) const {
    c.Set(L"theme.brand", brand);
    c.Set(L"theme.accent", accent);
    c.Set(L"theme.background", backgroundPath);
    c.SetInt(L"theme.timeout", timeoutSec);
    c.SetInt(L"theme.win11bypass", win11Bypass ? 1 : 0);
    // drop old alias.* / unattend.* lines then re-add
    std::vector<std::pair<Str, Str>> keep;
    for (auto& p : c.kv) if (p.first.rfind(L"alias.", 0) != 0 && p.first.rfind(L"unattend.", 0) != 0) keep.push_back(p);
    c.kv = keep;
    for (auto& a : aliases) {
        if (!a.alias.empty()) c.Set(L"alias." + a.relPath, a.alias);
        if (!a.unattendRel.empty()) c.Set(L"unattend." + a.relPath, a.unattendRel);
    }
}

Str DriveRelPath(const Str& driveLetter, const Str& fullPath) {
    Str rel = fullPath;
    if (rel.size() >= 2 && ToLower(rel.substr(0, 2)) == ToLower(driveLetter.substr(0, 2))) rel = rel.substr(2);
    for (auto& ch : rel) if (ch == L'\\') ch = L'/';
    if (rel.empty() || rel[0] != L'/') rel = L"/" + rel;
    return rel;
}

static Str Darken(const Str& hex) {
    if (hex.size() != 7) return L"#0B1220";
    int r = wcstol(hex.substr(1, 2).c_str(), nullptr, 16), g = wcstol(hex.substr(3, 2).c_str(), nullptr, 16), b = wcstol(hex.substr(5, 2).c_str(), nullptr, 16);
    return Format(L"#%02X%02X%02X", r / 4 + 6, g / 4 + 10, b / 4 + 20);
}

static Str BuildThemeTxt(const ThemeSettings& t, const Str& bgFile) {
    Str s;
    s += L"# Generated by IsoDeck — GRUB2 gfxmenu theme\n";
    s += L"desktop-image: \"" + bgFile + L"\"\n";
    s += L"desktop-image-scale-method: \"stretch\"\n";
    s += L"desktop-color: \"" + Darken(t.accent) + L"\"\n";
    s += L"title-text: \"\"\n";
    s += L"terminal-left: \"0\"\nterminal-top: \"0\"\nterminal-width: \"100%\"\nterminal-height: \"100%\"\n";
    s += L"terminal-border: \"0\"\n\n";
    s += L"+ boot_menu {\n"
         L"  left = 8%\n  top = 24%\n  width = 84%\n  height = 56%\n"
         L"  item_color = \"#C7D1E3\"\n"
         L"  selected_item_color = \"#FFFFFF\"\n"
         L"  item_height = 36\n  item_padding = 6\n  item_spacing = 8\n"
         L"  icon_width = 32\n  icon_height = 32\n  item_icon_space = 14\n"
         L"  scrollbar = true\n  scrollbar_width = 6\n"
         L"}\n\n";
    s += L"+ progress_bar {\n"
         L"  id = \"__timeout__\"\n  left = 8%\n  top = 84%\n  width = 84%\n  height = 6\n"
         L"  fg_color = \"" + t.accent + L"\"\n  bg_color = \"#1A2438\"\n  border_color = \"#1A2438\"\n  text_color = \"#7F8EA3\"\n"
         L"  show_text = false\n"
         L"}\n\n";
    s += L"+ label {\n  left = 0\n  top = 88%\n  width = 100%\n  align = \"center\"\n"
         L"  color = \"" + t.accent + L"\"\n  text = \"" + t.brand + L"\"\n}\n\n";
    s += L"+ label {\n  left = 0\n  top = 92%\n  width = 100%\n  align = \"center\"\n"
         L"  color = \"#7F8EA3\"\n  text = \"Enter: Boot   F2: Power   F3: Tree view   F5: Tools   F6: Extra menu\"\n}\n";
    return s;
}

static Str BuildVentoyJson(const ThemeSettings& t) {
    Str j = L"{\n";
    j += L"  \"control\": [\n";
    j += Format(L"    { \"VTOY_MENU_TIMEOUT\": \"%d\" },\n", t.timeoutSec);
    j += L"    { \"VTOY_DEFAULT_MENU_MODE\": \"0\" },\n";
    j += L"    { \"VTOY_FILT_DOT_UNDERSCORE_FILE\": \"1\" },\n";
    j += Format(L"    { \"VTOY_WIN11_BYPASS_CHECK\": \"%d\" },\n", t.win11Bypass ? 1 : 0);
    j += Format(L"    { \"VTOY_WIN11_BYPASS_NRO\": \"%d\" }\n", t.win11Bypass ? 1 : 0);
    j += L"  ],\n";
    j += L"  \"theme\": {\n";
    j += L"    \"file\": \"/ventoy/theme/isodeck/theme.txt\",\n";
    j += L"    \"gfxmode\": \"1920x1080,1600x900,1366x768,1280x720,1024x768\",\n";
    j += L"    \"display_mode\": \"GUI\",\n";
    j += L"    \"ventoy_left\": \"0%\",\n    \"ventoy_top\": \"200%\",\n";   // pushed off-screen: no engine name/version on the boot screen
    j += L"    \"ventoy_color\": \"" + t.accent + L"\"\n";
    j += L"  }";
    Str alias, autoI;
    for (auto& a : t.aliases) {
        if (!a.alias.empty()) alias += (alias.empty() ? L"" : L",\n") + Str(L"    { \"image\": \"") + JsonEscape(a.relPath) + L"\", \"alias\": \"" + JsonEscape(a.alias) + L"\" }";
        if (!a.unattendRel.empty()) autoI += (autoI.empty() ? L"" : L",\n") + Str(L"    { \"image\": \"") + JsonEscape(a.relPath) + L"\", \"template\": \"" + JsonEscape(a.unattendRel) + L"\" }";
    }
    if (!alias.empty()) j += L",\n  \"menu_alias\": [\n" + alias + L"\n  ]";
    if (!autoI.empty()) j += L",\n  \"auto_install\": [\n" + autoI + L"\n  ]";
    j += L"\n}\n";
    return j;
}

bool ApplyTheme(const Str& drive, const ThemeSettings& t, Str* error) {
    Str root = drive.substr(0, 2);
    Str themeDir = root + L"\\ventoy\\theme\\isodeck";
    if (!MakeDirs(themeDir)) { if (error) *error = LastErrorText(); return false; }

    // background
    Str bgName = L"background.png";
    bool wrote = false;
    if (!t.backgroundPath.empty() && FileExists(t.backgroundPath)) {
        bgName = EndsWithNoCase(t.backgroundPath, L".png") ? L"background.png" : L"background.jpg";
        DeleteFileSafe(JoinPath(themeDir, L"background.png")); DeleteFileSafe(JoinPath(themeDir, L"background.jpg"));
        wrote = CopyFileW(t.backgroundPath.c_str(), JoinPath(themeDir, bgName).c_str(), FALSE) != 0;
    }
    if (!wrote) {
        std::string png;
        if (!LoadResourceBytes(IDR_BACKGROUND, L"PACKAGE", png)) { if (error) *error = L"background resource missing"; return false; }
        DeleteFileSafe(JoinPath(themeDir, L"background.jpg"));
        if (!WriteFileBytes(JoinPath(themeDir, L"background.png"), png)) { if (error) *error = LastErrorText(); return false; }
        bgName = L"background.png";
    }
    if (!WriteFileBytes(JoinPath(themeDir, L"theme.txt"), WideToUtf8(BuildThemeTxt(t, bgName)))) { if (error) *error = LastErrorText(); return false; }
    if (!WriteFileBytes(root + L"\\ventoy\\ventoy.json", WideToUtf8(BuildVentoyJson(t)))) { if (error) *error = LastErrorText(); return false; }
    SetFileAttributesW((root + L"\\ventoy").c_str(), FILE_ATTRIBUTE_HIDDEN | FILE_ATTRIBUTE_SYSTEM);   // keep the engine folder out of sight
    SLOG(L"Theme applied to %s", root.c_str());
    return true;
}

